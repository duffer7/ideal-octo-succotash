/**
 * Типы для системы сезонов.
 *
 * Сезон — это набор уровней с общей темой (лето, осень, зима, весна).
 * Каждый уровень описывает: фон, падающие объекты и корзины-приёмники.
 */
import type { TranslationKey } from '../i18n';

/** Идентификаторы сезонов. Пока реализован только лето. */
export type SeasonId = 'summer' | 'autumn' | 'winter' | 'spring';

/**
 * Способ задания картинки ассета.
 * - `key` — зарегистрированный в Phaser ключ текстуры (после load.image/atlas).
 * - `path` — путь к файлу (используется для предзагрузки, если нужно).
 *
 * Пока картинок нет — оставляем пустым, и игра рисует цветную заглушку.
 */
export interface AssetRef {
  /** Ключ текстуры в Phaser. Если текстура не загружена — рисуется заглушка. */
  key?: string;
  /** Путь к файлу ассета (для PreloadScene). */
  path?: string;
}

/** Категория объекта: определяет, в какую корзину его нужно положить. */
export interface Category {
  /** Стабильный идентификатор категории (например, 'sand', 'water'). */
  id: string;
  /** Цвет-заглушка (используется, пока нет картинки). */
  color: number;
  /** Ключ локализации для названия категории. */
  labelKey: TranslationKey;
}

/** Корзина-приёмник на экране. */
export interface Basket {
  /** Какая категория кладётся в эту корзину. */
  categoryId: string;
  /** Цвет-заглушка корзины. */
  color: number;
  /** Картинка корзины (опционально). */
  image?: AssetRef;
  /**
   * Картинка-метка на корзине (например, ракушка нужной категории).
   * Если задана и загружена — показывается вместо текстовой подписи.
   */
  labelImage?: AssetRef;
  /** Ключ локализации названия корзины. */
  labelKey: TranslationKey;
}
/** Падающий объект. */
export interface FallingItem {
  /** В какую категорию/корзину относится объект. */
  categoryId: string;
  /** Цвет-заглушка. */
  color: number;
  /** Картинка объекта (опционально). */
  image?: AssetRef;
}

/** Описание одного уровня. */
export interface LevelConfig {
  /** Номер уровня внутри сезона (1-based). */
  number: number;
  /** Фон сцены (картинка опциональна — есть цветной фолбэк). */
  background: AssetRef & { color: number };
  /**
   * Слой облаков поверх фона (опционально).
   * Рисуется отдельно от фона, чтобы облака и фон жили независимо.
   */
  clouds?: AssetRef;
  /** Категории объектов. */
  categories: Category[];
  /** Корзины-приёмники. */
  baskets: Basket[];
  /**
   * Вероятности появления объектов по категориям.
   * Например, { sand: 0.5, water: 0.5 } — поровну.
   * Если не задано — распределение равномерное.
   */
  spawnWeights?: Record<string, number>;
  /** Сколько объектов нужно рассортировать, чтобы пройти уровень. */
  targetCount: number;
  /** Как часто падают объекты, мс. */
  spawnIntervalMs: number;
  /** Скорость падения, пикселей в секунду. */
  fallSpeed: number;
}

/** Описание сезона. */
export interface Season {
  id: SeasonId;
  /** Ключ локализации названия сезона. */
  nameKey: TranslationKey;
  /** Количество уровней в сезоне. */
  levelCount: number;
  /** Уровни сезона. */
  levels: LevelConfig[];
}



