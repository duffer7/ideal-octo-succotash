/**
 * Типы для системы сезонов.
 *
 * Сезон — это набор уровней с общей темой (лето, осень, зима, весна).
 * Каждый уровень описывает: фон, падающие объекты и корзины-приёмники.
 *
 * Собираемым предметам соответствует своя корзина: ракушку кладут в её
 * корзину, бутылку и банку — в одну общую мусорную. Камни не собирают —
 * они падают мимо.
 */
import type { TranslationKey } from '../i18n';

/** Идентификаторы сезонов. Пока реализован только лето. */
export type SeasonId = 'summer' | 'autumn' | 'winter' | 'spring';

/**
 * Способ задания картинки ассета.
 * - `key` — зарегистрированный в Phaser ключ текстуры (после load.image/atlas).
 * - `path` — путь к файлу (используется для предзагрузки, если нужно).
 *
 * Пока картинок нет — оставляем пустым, и игра рисует цветную заглушку.
 */
export interface AssetRef {
  /** Ключ текстуры в Phaser. Если текстура не загружена — рисуется заглушка. */
  key?: string;
  /** Путь к файлу ассета (для PreloadScene). */
  path?: string;
}

/** Корзина-приёмник на экране. */
export interface Basket {
  /** К какому предмету относится эта корзина (совпадает с FallingItem.id). */
  itemId: string;
  /** Цвет-заглушка корзины. */
  color: number;
  /** Картинка корзины (опционально). */
  image?: AssetRef;
  /**
   * Картинка-метка на корзине (например, ракушка, которую сюда кладут).
   * Если задана и загружена — показывается вместо текстовой подписи.
   */
  labelImage?: AssetRef;
  /**
   * Несколько меток на одной корзине (бутылка и банка на общей мусорке).
   * Если заданы — показываются вместо `labelImage`.
   */
  labelImages?: AssetRef[];
  /** Ключ локализации названия корзины. */
  labelKey: TranslationKey;
  /**
   * Стоит отдельно от общего ряда, чуть в стороне (мусорная корзина).
   * Остальные корзины из-за этого не делят с ней ширину и остаются крупнее.
   */
  aside?: boolean;
}

/** Падающий объект. Собираемые предметы попадают в корзину с тем же id. */
export interface FallingItem {
  /** Уникальный идентификатор предмета (совпадает с Basket.itemId). */
  id: string;
  /** Цвет-заглушка. */
  color: number;
  /** Картинка объекта (опционально). */
  image?: AssetRef;
  /**
   * Несколько картинок для одного предмета (например, разные камни).
   * При появлении выбирается случайная из списка.
   */
  images?: AssetRef[];
  /**
   * Относительный вес появления (чем больше — тем чаще падает).
   * Если не задан — считается равным 1.
   */
  weight?: number;
  /**
   * Цена предмета в очках. Начисляется при верном сборе
   * (с множителем серии) и частично снимается при ошибке.
   * 0 — предмет не приносит очков (камни).
   */
  points?: number;
  /**
   * С какого уровня появляется объект (1-based).
   * Позволяет вводить новые предметы постепенно: например, камни — с 3 ур.
   * Если не задано — объект доступен на всех уровнях сезона.
   */
  fromLevel?: number;
  /**
   * Особый эффект при верной сортировке.
   * `freeze` — редкий предмет без своей корзины: его кладут в любую,
   * и на пару секунд все предметы падают медленнее.
   */
  effect?: 'freeze';
}

/** Название категории (семантическая группа предметов: песок, вода, мусор). */
export interface Category {
  /** Идентификатор категории (совпадает с id предметов этой категории). */
  id: string;
  /** Цвет-заглушка категории. */
  color: number;
  /** Ключ локализации названия категории. */
  labelKey: TranslationKey;
}

/** Описание одного уровня сезона. */
export interface LevelConfig {
  /** Номер уровня (1-based). */
  number: number;
  /** Фон уровня: картинка (если загружена) или цвет-заглушка. */
  background: AssetRef & { color: number };
  /**
   * Слой облаков поверх фона (опционально).
   * Рисуется отдельно от фона, чтобы облака и фон жили независимо.
   */
  clouds?: AssetRef;
  /** Категории предметов, доступные на уровне. */
  categories: Category[];
  /** Корзины-приёмники (по одной на каждый доступный предмет). */
  baskets: Basket[];
  /**
   * Сколько верных сборов нужно в ежедневном задании и для расчёта
   * длины уровня. Победа обычного уровня считается по `targetScore`.
   */
  targetCount: number;
  /** Сколько очков нужно набрать, чтобы пройти уровень. */
  targetScore: number;
  /** Как часто падают объекты, мс. */
  spawnIntervalMs: number;
  /** Скорость падения, пикселей в секунду. */
  fallSpeed: number;
  /** Относительные веса появления предметов по категориям (сумма ≈ 1). */
  spawnWeights: Record<string, number>;
}

/** Описание сезона. */
export interface Season {
  id: SeasonId;
  /** Ключ локализации названия сезона. */
  nameKey: TranslationKey;
  /** Количество уровней в сезоне. */
  levelCount: number;
  /** Уровни сезона. */
  levels: LevelConfig[];
}
