/**
 * Преобразует цвет Phaser (число) в CSS-строку вида '#rrggbb'.
 * Единая точка конверсии — чтобы hex-строки не появлялись «руками».
 */
export function toCss(color: number): string {
  return `#${color.toString(16).padStart(6, '0')}`;
}

/**
 * Возвращает тот же цвет с заданной прозрачностью в виде CSS 'rgba(...)'.
 * Удобно для теней/оверлеев, задаваемых строкой.
 */
export function toCssRgba(color: number, alpha: number): string {
  const r = (color >> 16) & 0xff;
  const g = (color >> 8) & 0xff;
  const b = color & 0xff;
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}
